/**
 * DiameterForge Pro - Multi-Platform Configuration Synthesizer
 * Generates verified production syntax for:
 * 1. FreeDiameter Daemon (freeDiameter.conf)
 * 2. Open5GS HSS/PCRF Diameter Configuration (hss.yaml)
 * 3. Cisco cDRA / ASR 5500 Diameter Routing Agent
 * 4. Juniper Junos MX Security Filter for Port 3868
 * 5. Prometheus Diameter Exporter & Telemetry Alerting Rules
 */

(function (root, factory) {
  if (typeof define === 'function' && define.amd) {
    define([], factory);
  } else if (typeof module === 'object' && module.exports) {
    module.exports = factory();
  } else {
    root.DiameterConfigSynthesizer = factory();
  }
}(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  function generateFreeDiameter(cfg) {
    const originHost = cfg.originHost || 'dra01.carrier.net';
    const originRealm = cfg.originRealm || 'carrier.net';
    const listenIp1 = cfg.listenIp1 || '192.168.50.10';
    const listenIp2 = cfg.listenIp2 || '192.168.60.10';
    const peerHost = cfg.peerHost || 'peer-dea.roaming-ipx.net';
    const peerIp = cfg.peerIp || '198.51.100.25';
    const peerRealm = cfg.destRealm || 'roaming-ipx.net';
    const watchdogSec = parseInt(cfg.watchdogTimerSec, 10) || 30;

    let out = [];
    out.push('# ==============================================================================');
    out.push('# FreeDiameter Production Daemon Configuration (freeDiameter.conf)');
    out.push('# Generated by DiameterForge Pro v1.0.0');
    out.push('# ==============================================================================');
    out.push('');
    out.push(`Identity = "${originHost}";`);
    out.push(`Realm = "${originRealm}";`);
    out.push('Port = 3868;');
    out.push(`SecPort = 5868;`);
    out.push('');
    out.push('# SCTP Multi-Homing Listen Endpoints');
    out.push(`ListenOn = "${listenIp1}";`);
    if (cfg.sctpMultiHomed) {
      out.push(`ListenOn = "${listenIp2}";`);
    }
    out.push('');
    out.push('# Cryptographic TLS / mTLS Security');
    if (cfg.encryptionEnabled) {
      out.push('TLS_Cred = "/etc/freeDiameter/cert.pem", "/etc/freeDiameter/key.pem";');
      out.push('TLS_CA = "/etc/freeDiameter/ca.pem";');
      out.push('TLS_DH_File = "/etc/freeDiameter/dh.pem";');
    } else {
      out.push('No_TLS;');
    }
    out.push('');
    out.push('# Timers & State Machine');
    out.push(`TcTimer = ${watchdogSec};`);
    out.push(`TwTimer = ${watchdogSec};`);
    out.push('');
    out.push('# Peer Association');
    out.push(`ConnectPeer = "${peerHost}" {`);
    out.push(`    ConnectTo = "${peerIp}";`);
    out.push(`    No_SCTP = 0; # Enforce SCTP`);
    if (cfg.encryptionEnabled) {
      out.push('    No_TLS = 0;');
    } else {
      out.push('    No_TLS = 1;');
    }
    out.push(`    Realm = "${peerRealm}";`);
    out.push('};');
    out.push('');

    return out.join('\n');
  }

  function generateOpen5GS(cfg) {
    const originHost = cfg.originHost || 'hss.carrier.net';
    const originRealm = cfg.originRealm || 'carrier.net';
    const listenIp1 = cfg.listenIp1 || '192.168.50.10';

    return `# ==============================================================================
# Open5GS HSS / PCRF Diameter Configuration (hss.yaml)
# Generated by DiameterForge Pro v1.0.0
# ==============================================================================

hss:
  freeDiameter:
    identity: ${originHost}
    realm: ${originRealm}
    listen_on: ${listenIp1}
    port: 3868
    tls:
      enabled: ${cfg.encryptionEnabled ? 'true' : 'false'}
      cert: /etc/open5gs/cert.pem
      key: /etc/open5gs/key.pem
      ca: /etc/open5gs/ca.pem

logger:
  file: /var/log/open5gs/hss.log
  level: info
`;
  }

  function generateCisco(cfg) {
    const originHost = cfg.originHost || 'dra01.carrier.net';
    const originRealm = cfg.originRealm || 'carrier.net';
    const peerHost = cfg.peerHost || 'peer-dea.roaming-ipx.net';
    const peerRealm = cfg.destRealm || 'roaming-ipx.net';

    let out = [];
    out.push('! ==============================================================================');
    out.push('! Cisco cDRA / ASR 5500 Diameter Routing Agent Configuration');
    out.push('! Generated by DiameterForge Pro v1.0.0');
    out.push('! ==============================================================================');
    out.push('!');
    out.push('context diameter-core');
    out.push(`  diameter endpoint EP-CORE`);
    out.push(`    origin-host ${originHost}`);
    out.push(`    origin-realm ${originRealm}`);
    if (cfg.sctpMultiHomed) {
      out.push('    transport sctp multi-homing enabled');
    }
    if (cfg.topologyHidingEnabled) {
      out.push('    topology-hiding enabled');
      out.push('    topology-hiding mode randomize-origin-host');
    }
    out.push('  exit');
    out.push('!');
    out.push(`  diameter peer ${peerHost}`);
    out.push(`    realm ${peerRealm}`);
    if (cfg.commandScreeningEnabled) {
      out.push('    screening-policy GSMA-FS19-RESTRICTED');
    }
    out.push('    watchdog-timer 30');
    out.push('  exit');
    out.push('exit');
    out.push('!');

    if (cfg.coppEnabled) {
      out.push('! Control Plane Policing for Port 3868');
      out.push('ip access-list ACL-COPP-DIAMETER');
      out.push(' permit sctp any any eq 3868');
      out.push(' permit tcp any any eq 3868');
      out.push('!');
      out.push('policy-map POLICY-COPP-DIAMETER');
      out.push(' class ACL-COPP-DIAMETER');
      out.push('  police rate 25000 pps conform-action transmit exceed-action drop');
      out.push('!');
    }

    return out.join('\n');
  }

  function generateJunos(cfg) {
    const listenIp1 = cfg.listenIp1 || '192.168.50.10';

    let out = [];
    out.push('# ==============================================================================');
    out.push('# Juniper Junos MX Diameter Security Filter & Rate-Limiter');
    out.push('# Generated by DiameterForge Pro v1.0.0');
    out.push('# ==============================================================================');
    out.push('');
    out.push('set firewall family inet filter FILTER-DIAMETER-EDGE term ALLOW-TRUSTED-DIAMETER from destination-address ' + listenIp1);
    out.push('set firewall family inet filter FILTER-DIAMETER-EDGE term ALLOW-TRUSTED-DIAMETER from protocol sctp');
    out.push('set firewall family inet filter FILTER-DIAMETER-EDGE term ALLOW-TRUSTED-DIAMETER from destination-port 3868');
    if (cfg.coppEnabled) {
      out.push('set firewall family inet filter FILTER-DIAMETER-EDGE term ALLOW-TRUSTED-DIAMETER then policer POLICER-DIAMETER-25K');
      out.push('set firewall policer POLICER-DIAMETER-25K if-exceeding bandwidth-limit 100m burst-size-limit 128k');
      out.push('set firewall policer POLICER-DIAMETER-25K then discard');
    }
    out.push('set firewall family inet filter FILTER-DIAMETER-EDGE term ALLOW-TRUSTED-DIAMETER then accept');
    out.push('');
    out.push('set firewall family inet filter FILTER-DIAMETER-EDGE term DROP-UNAUTHORIZED-PORT3868 from destination-port 3868');
    out.push('set firewall family inet filter FILTER-DIAMETER-EDGE term DROP-UNAUTHORIZED-PORT3868 then log');
    out.push('set firewall family inet filter FILTER-DIAMETER-EDGE term DROP-UNAUTHORIZED-PORT3868 then discard');
    out.push('');

    return out.join('\n');
  }

  function generatePrometheus(cfg) {
    return `# ==============================================================================
# Prometheus Diameter Exporter & Telemetry Alerting Rules
# Generated by DiameterForge Pro v1.0.0
# ==============================================================================

groups:
  - name: diameter_signaling_alerts
    rules:
      - alert: DiameterPeerAssociationDown
        expr: diameter_peer_state{state!="OPEN"} == 1
        for: 15s
        labels:
          severity: critical
          tier: telecom-aaa
        annotations:
          summary: "Diameter Peer Connection Severed: {{ $labels.peer_host }}"
          description: "SCTP association with {{ $labels.peer_host }} is down. Watchdog heartbeat timeout or IPX link failure."

      - alert: DiameterHighErrorRate5001
        expr: rate(diameter_messages_total{result_code="5001"}[2m]) > 20
        for: 1m
        labels:
          severity: critical
          tier: charging
        annotations:
          summary: "Elevated DIAMETER_AVP_UNSUPPORTED (5001) Errors"
          description: "High volume of 5001 rejections detected. Likely proprietary AVP with M-bit=1 transmitted to unsupporting peer."

      - alert: DiameterWatchdogLatencyHigh
        expr: histogram_quantile(0.99, rate(diameter_dwr_response_time_seconds_bucket[5m])) > 2.0
        for: 2m
        labels:
          severity: warning
          tier: ipx-interconnect
        annotations:
          summary: "Elevated DWR Watchdog Round-Trip Time on {{ $labels.peer_realm }}"
          description: "99th percentile DWR/DWA round trip time exceeds 2.0 seconds. Possible IPX congestion or peer queuing backlog."
`;
  }

  return {
    generateFreeDiameter,
    generateOpen5GS,
    generateCisco,
    generateJunos,
    generatePrometheus
  };
}));
